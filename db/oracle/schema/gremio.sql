CREATE TABLE CIUDAD (
  ciudad_id   NUMBER(3)    CONSTRAINT ciudad_pk PRIMARY KEY,
  nombre      VARCHAR2(30) CONSTRAINT ciudad_nombre_nn NOT NULL,
  region      VARCHAR2(30)
);

CREATE TABLE CLASE (
  clase_id            NUMBER(3)    CONSTRAINT clase_pk PRIMARY KEY,
  nombre              VARCHAR2(20) CONSTRAINT clase_nombre_nn NOT NULL
                                   CONSTRAINT clase_nombre_uk UNIQUE,
  dado_golpe          NUMBER(2)    CONSTRAINT clase_dado_ck CHECK (dado_golpe IN (6, 8, 10, 12)),
  atributo_principal  VARCHAR2(15)
);

CREATE TABLE GREMIO (
  gremio_id  NUMBER(2)    CONSTRAINT gremio_pk PRIMARY KEY,
  nombre     VARCHAR2(40) CONSTRAINT gremio_nombre_nn NOT NULL,
  ciudad_id  NUMBER(3)    CONSTRAINT gremio_ciudad_fk REFERENCES CIUDAD,
  fundado    DATE
);

CREATE TABLE AVENTURERO (
  aventurero_id  NUMBER(4)    CONSTRAINT aventurero_pk PRIMARY KEY,
  nombre         VARCHAR2(20) CONSTRAINT aventurero_nombre_nn NOT NULL,
  apodo          VARCHAR2(30),
  raza           VARCHAR2(15),
  clase_id       NUMBER(3)    CONSTRAINT aventurero_clase_fk REFERENCES CLASE,
  mentor_id      NUMBER(4)    CONSTRAINT aventurero_mentor_fk REFERENCES AVENTURERO,
  gremio_id      NUMBER(2)    CONSTRAINT aventurero_gremio_fk REFERENCES GREMIO,
  nivel          NUMBER(2)    DEFAULT 1 CONSTRAINT aventurero_nivel_ck CHECK (nivel BETWEEN 1 AND 20),
  oro            NUMBER(8,2),
  hp             NUMBER(4),
  hp_max         NUMBER(4),
  fecha_ingreso  DATE,
  CONSTRAINT aventurero_hp_ck CHECK (hp BETWEEN 0 AND hp_max)
);

CREATE TABLE RANGO (
  rango_id   NUMBER(2)    CONSTRAINT rango_pk PRIMARY KEY,
  titulo     VARCHAR2(20) CONSTRAINT rango_titulo_nn NOT NULL,
  nivel_min  NUMBER(2),
  nivel_max  NUMBER(2),
  CONSTRAINT rango_limites_ck CHECK (nivel_min <= nivel_max)
);

CREATE TABLE OBJETO (
  objeto_id  NUMBER(5)    CONSTRAINT objeto_pk PRIMARY KEY,
  nombre     VARCHAR2(40) CONSTRAINT objeto_nombre_nn NOT NULL,
  tipo       VARCHAR2(12) CONSTRAINT objeto_tipo_ck
             CHECK (tipo IN ('ARMA', 'ARMADURA', 'POCION', 'ANILLO', 'PERGAMINO')),
  rareza     VARCHAR2(12) CONSTRAINT objeto_rareza_ck
             CHECK (rareza IN ('COMUN', 'RARA', 'EPICA', 'LEGENDARIA'))
);

CREATE TABLE PRECIO_OBJETO (
  objeto_id    NUMBER(5)  CONSTRAINT precio_objeto_fk REFERENCES OBJETO,
  fecha_desde  DATE,
  fecha_hasta  DATE,
  precio       NUMBER(8,2) CONSTRAINT precio_precio_nn NOT NULL,
  precio_min   NUMBER(8,2),
  CONSTRAINT precio_objeto_pk PRIMARY KEY (objeto_id, fecha_desde),
  CONSTRAINT precio_min_ck CHECK (precio_min <= precio),
  CONSTRAINT precio_fechas_ck CHECK (fecha_hasta IS NULL OR fecha_desde < fecha_hasta)
);

CREATE TABLE MISION (
  mision_id          NUMBER(4)    CONSTRAINT mision_pk PRIMARY KEY,
  titulo             VARCHAR2(60) CONSTRAINT mision_titulo_nn NOT NULL,
  gremio_id          NUMBER(2)    CONSTRAINT mision_gremio_fk REFERENCES GREMIO,
  dificultad         NUMBER(1)    CONSTRAINT mision_dificultad_ck CHECK (dificultad BETWEEN 1 AND 5),
  recompensa         NUMBER(8,2),
  fecha_publicacion  DATE,
  fecha_cierre       DATE,
  estado             VARCHAR2(12) DEFAULT 'ABIERTA' CONSTRAINT mision_estado_ck
                     CHECK (estado IN ('ABIERTA', 'COMPLETADA', 'FALLIDA'))
);

CREATE TABLE PARTICIPACION (
  mision_id      NUMBER(4) CONSTRAINT part_mision_fk REFERENCES MISION,
  aventurero_id  NUMBER(4) CONSTRAINT part_aventurero_fk REFERENCES AVENTURERO,
  rol            VARCHAR2(12) CONSTRAINT part_rol_ck CHECK (rol IN ('LIDER', 'APOYO', 'EXPLORADOR')),
  CONSTRAINT participacion_pk PRIMARY KEY (mision_id, aventurero_id)
);

CREATE TABLE BOTIN (
  mision_id  NUMBER(4) CONSTRAINT botin_mision_fk REFERENCES MISION,
  nro        NUMBER(3),
  objeto_id  NUMBER(5) CONSTRAINT botin_objeto_fk REFERENCES OBJETO,
  cantidad   NUMBER(4) DEFAULT 1,
  CONSTRAINT botin_pk PRIMARY KEY (mision_id, nro)
);

